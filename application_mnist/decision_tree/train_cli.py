"""Reproducible command-line alternative to DecisionTree_workbook.ipynb.

Example:
python -m application_mnist.decision_tree.train_cli \
    --data application_mnist/data/processed/3_vs_8_g7_t20_seed42.npz

Must be run from the repository root. Train/validation choice precedes test evaluation.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from application_mnist.data.pipeline import load_prepared
from .training import tune_trees, split_metrics, save_tuning_table, save_model_bundle
from .boolean_formula import tree_to_dnf, assert_equivalent, export_formulas


def _depth_list(value):
    return tuple(None if s.strip().lower() == "none" else int(s)
                 for s in value.split(","))


def main(argv= None):
    parser = argparse.ArgumentParser(description="Train and export Boolean MNIST tree")
    parser.add_argument("--data", type=Path, required=True, help="Prepared .npz generated by stage 1")
    parser.add_argument("--out", type=Path, help="Output directory (defaults under decision_tree/outputs)")
    parser.add_argument("--depths", default="2,3,4,5,6,8,None")
    parser.add_argument("--min-leaf-sizes", default="1,5,10,20")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)

    data = load_prepared(args.data)
    out = args.out or Path(__file__).resolve().parent / "outputs" / args.data.stem
    model, settings, rows = tune_trees(
        data, depths=_depth_list(args.depths),
        min_leaf_sizes=tuple(int(x) for x in args.min_leaf_sizes.split(",")), seed=args.seed)
    print("Selected using validation:", settings)
    print("Train:", split_metrics(model, data, "train"))
    print("Validation:", split_metrics(model, data, "val"))
    save_tuning_table(rows, out / "validation_grid.csv")
    feature_names = [str(x) for x in data["feature_names"]]
    yes = tree_to_dnf(model, feature_names)
    no = tree_to_dnf(model, feature_names, positive_class=0)
    for split in ("train", "val"):
        assert_equivalent(model, yes, data[f"{split}_features"])
    # Final untouched test evaluation after validation selection
    test_metrics = split_metrics(model, data, "test")
    assert_equivalent(model, yes, data["test_features"])
    for split in ("train", "val", "test"):
        x = data[f"{split}_features"]
        assert (yes.evaluate(x) + no.evaluate(x) == 1).all()
    print("Final test:", test_metrics)
    save_model_bundle(model, settings, data, out, test_results=test_metrics)
    export_formulas(model, feature_names, out)
    print("Saved artifacts to", out)


if __name__ == "__main__":
    main()
